#!/usr/bin/env python3
"""Regenerate the research-papers website index from the manuscripts in files/.

Run from this folder (files/papers-website/) or anywhere:
    python3 build-index.py
Reads ../2026-*.md + ../leadforge-manuscript-v1.md, extracts each title,
and writes index.html next to this script. Links are relative (../<file>.pdf),
so the page works locally and on GitHub Pages serving this repo.
Re-run after every daily papers run to pick up new manuscripts.
"""
import html
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
FILES = HERE.parent

SUPERSEDED = {
    "2026-11-02-health-thymoquinone-aldose-reductase.md": "Superseded by v2 (4 Nov)",
    "2026-11-02-health-dual-ar-sglt2.md": "Superseded by v2 (4 Nov)",
}
READY = {
    "2026-11-04-health-thymoquinone-aldose-reductase-v2.md": "v2 — ready to submit",
    "2026-11-04-health-dual-ar-sglt2-v2.md": "v2 — ready to submit",
}

TRACK_LABEL = {"health": "Health", "brain": "Brain", "space": "Space"}


def title_of(path: Path) -> str:
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def rows():
    out = []
    for path in sorted(FILES.glob("2026-*.md"), reverse=True):
        m = re.match(r"(2026-\d\d-\d\d)-(health|brain|space)-", path.name)
        if not m:
            continue
        date, track = m.group(1), m.group(2)
        pdf = path.with_suffix(".pdf").name
        status = SUPERSEDED.get(path.name, READY.get(path.name, "Draft — not submitted"))
        out.append((date, track, title_of(path), path.name, pdf, status))
    lf = FILES / "leadforge-manuscript-v1.md"
    if lf.exists():
        out.append(("2026-11-01", "health", title_of(lf), lf.name,
                    "leadforge-manuscript-v1.pdf", "Draft — not submitted"))
    return out


def main():
    rs = rows()
    counts = {t: sum(1 for r in rs if r[1] == t) for t in ("health", "brain", "space")}
    total = len(rs)
    items = []
    for date, track, title, md, pdf, status in rs:
        items.append(
            f'<li><span class="date">{date}</span> '
            f'<span class="badge {track}">{TRACK_LABEL[track]}</span> '
            f'<span class="t">{html.escape(title)}</span> '
            f'<span class="links"><a href="../{html.escape(pdf)}">PDF</a> · '
            f'<a href="../{html.escape(md)}">Markdown</a></span> '
            f'<span class="status">{html.escape(status)}</span></li>'
        )
    body = "\n".join(items)
    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>Research Papers — Zubair Ali</title>
<style>
body{{font-family:Georgia,serif;max-width:900px;margin:0 auto;padding:24px 18px;color:#1c1c1c;line-height:1.5}}
h1{{font-size:30px;margin:0 0 4px}} .sub{{color:#555;margin:0 0 16px}}
.counts{{display:flex;gap:10px;flex-wrap:wrap;margin:14px 0}}
.counts b{{background:#f0ead9;border:1px solid #ddd;padding:8px 12px;border-radius:10px;font-family:system-ui}}
ul{{list-style:none;padding:0}} li{{border-top:1px solid #e5e0d5;padding:12px 0}}
.date{{font-family:system-ui;font-size:13px;color:#666}} .badge{{font-family:system-ui;font-size:11px;font-weight:700;padding:2px 8px;border-radius:999px;margin:0 6px}}
.health{{background:#dcefe0}} .brain{{background:#dde8f7}} .space{{background:#efe3f7}}
.t{{font-weight:600}} .links{{font-family:system-ui;font-size:13px;white-space:nowrap}}
.status{{display:block;font-family:system-ui;font-size:12px;color:#777}}
.note{{background:#fdf6e3;border:1px solid #e8d9a0;padding:12px;border-radius:10px;font-size:14px}}
a{{color:#0b5cad}}
</style>
</head>
<body>
<h1>Research Papers</h1>
<p class="sub">Zubair Ali — Pharm-D, SMBBMU Larkana, Pakistan · ORCID 0009-0001-5921-7509</p>
<div class="counts"><b>{total} manuscripts</b><b>Health: {counts["health"]}</b><b>Brain: {counts["brain"]}</b><b>Space: {counts["space"]}</b></div>
<p class="note">AI-assisted drafts — <b>not peer-reviewed, not published, none submitted yet</b>. ChemRxiv submission is blocked at sign-in by a Cloudflare check; submitting is the author's own click after he approves a paper. New manuscripts are added here daily by the papers run. Papers #1 and #3 v2 are the two ready-to-submit manuscripts.</p>
<ul>
{body}
</ul>
<p class="sub">Updated 14 Nov 2026 · generated by files/papers-website/build-index.py — re-run it after each daily papers run.</p>
</body>
</html>
"""
    (HERE / "index.html").write_text(page, encoding="utf-8")
    print(f"wrote index.html: {total} papers "
          f"(health {counts['health']}, brain {counts['brain']}, space {counts['space']})")


if __name__ == "__main__":
    main()
